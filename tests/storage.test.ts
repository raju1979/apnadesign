import { test } from "node:test";
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { PGlite } from "@electric-sql/pglite";

test("project asset storage keeps uploads editor-only and reads project-scoped", async () => {
  const db = new PGlite();
  try {
    await db.exec(
      `create role anon; create role authenticated; create schema auth; create schema storage;
       create table auth.users(id uuid primary key);
       create function auth.uid() returns uuid language sql stable as $$ select (current_setting('request.jwt.claims',true)::jsonb->>'sub')::uuid $$;
       create function auth.jwt() returns jsonb language sql stable as $$ select current_setting('request.jwt.claims',true)::jsonb $$;
       grant usage on schema auth to authenticated; grant execute on all functions in schema auth to authenticated;
       create table storage.buckets(id text primary key,name text not null,public boolean not null,file_size_limit bigint,allowed_mime_types text[]);
       create table storage.objects(id bigint generated by default as identity primary key,bucket_id text not null,name text not null,owner_id uuid);
       create function storage.foldername(name text) returns text[] language sql immutable as $$ select case when position('/' in name)>0 then array[split_part(name,'/',1)] else array[]::text[] end $$;
       alter table storage.objects enable row level security;
       grant usage on schema storage to authenticated; grant select,insert on storage.objects to authenticated; grant execute on all functions in schema storage to authenticated;`,
    );
    for (const migration of [
      "20261010144239_20261010_accounts_permissions.sql",
      "20261010150529_anonymous_project_shares.sql",
      "20261010150704_harden_project_share_rpcs.sql",
      "20261010153146_formwork_asset_storage.sql",
      "20261010154812_formwork_asset_500kb_limit.sql",
    ])
      await db.exec(await readFile(`supabase/migrations/${migration}`, "utf8"));
    const users = [
      "11111111-1111-4111-8111-111111111111",
      "22222222-2222-4222-8222-222222222222",
      "33333333-3333-4333-8333-333333333333",
      "44444444-4444-4444-8444-444444444444",
      "55555555-5555-4555-8555-555555555555",
    ];
    for (const id of users)
      await db.query("insert into auth.users values($1)", [id]);
    async function as(index: number) {
      await db.exec("reset role");
      await db.query("select set_config('request.jwt.claims',$1,false)", [
        JSON.stringify({
          sub: users[index],
          email: [
            "owner@example.test",
            "editor@example.test",
            "viewer@example.test",
            "outsider@example.test",
            null,
          ][index],
        }),
      ]);
      await db.exec("set role authenticated");
    }
    await as(0);
    await db.exec(
      `insert into public.formwork_projects(id,title,document) values('asset-project','Assets','{"title":"Assets","shapes":[]}');
       insert into public.formwork_members values('asset-project','editor@example.test','editor'),('asset-project','viewer@example.test','viewer');
       insert into storage.objects(bucket_id,name) values('formwork-assets','asset-project/owner.png');`,
    );
    await as(1);
    await db.exec(
      `insert into storage.objects(bucket_id,name) values('formwork-assets','asset-project/editor.png')`,
    );
    await as(2);
    assert.equal(
      (
        await db.query(
          `select * from storage.objects where bucket_id='formwork-assets'`,
        )
      ).rows.length,
      2,
    );
    await assert.rejects(() =>
      db.exec(
        `insert into storage.objects(bucket_id,name) values('formwork-assets','asset-project/viewer.png')`,
      ),
    );
    await as(3);
    assert.equal(
      (
        await db.query(
          `select * from storage.objects where bucket_id='formwork-assets'`,
        )
      ).rows.length,
      0,
    );
    await as(0);
    await db.query("select public.create_project_share('asset-project',$1)", [
      "a".repeat(64),
    ]);
    await as(4);
    await db.query("select public.claim_project_share('asset-project',$1)", [
      "a".repeat(64),
    ]);
    assert.equal(
      (
        await db.query(
          `select * from storage.objects where bucket_id='formwork-assets'`,
        )
      ).rows.length,
      2,
    );
    await assert.rejects(() =>
      db.exec(
        `insert into storage.objects(bucket_id,name) values('formwork-assets','asset-project/guest.png')`,
      ),
    );
    await db.exec("reset role");
    const bucket = await db.query<{ public: boolean; file_size_limit: number }>(
      `select public,file_size_limit from storage.buckets where id='formwork-assets'`,
    );
    assert.equal(bucket.rows[0].public, false);
    assert.equal(bucket.rows[0].file_size_limit, 500000);
  } finally {
    await db.close();
  }
});
